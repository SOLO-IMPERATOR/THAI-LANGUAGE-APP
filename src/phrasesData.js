// Helper to breakdown Thai sentence words
function generateBreakdown(thai, ru_tr, ru) {
  const parts = thai.split(' ');
  if (parts.length > 1) {
    return parts.map((p, i) => ({
      thai_hidden: p,
      transcription_ru: ru_tr.split(' ')[i] || ru_tr,
      translation_ru: i === 0 ? ru : '—'
    }));
  }
  return [
    { thai_hidden: thai, transcription_ru: ru_tr, translation_ru: ru }
  ];
}

